#!/usr/bin/env python3
"""Generates src/layers/ra_data.js : Road Atlanta centre-line control points, elevation, corner markers.
Layout is a stylised Road Atlanta (clockwise, uphill front straight, T1 fast uphill right, T3/T4, Esses, T5, banked T6,
tight T7, long diagonal back straight with lazy T8/T9, T10a/b complex, T11 under the bridge, diving T12)."""
import math,json,sys
import numpy as np
from scipy.optimize import least_squares
SCALE=1.2
def prog(F,B,S2):
    return [('S',F,'FS'),('A',82,+95,'T1'),('S',70,''),('A',300,-8,'T2'),('S',50,''),('A',50,+55,'T3'),('A',70,-80,'T4'),('S',30,''),
    ('A',85,+40,'E1'),('A',70,-45,'E2'),('A',80,+45,'E3'),('A',65,-30,'E4'),('S',20,''),('A',55,+75,'T5'),('S',40,''),('A',110,+85,'T6'),
    ('S',120,''),('A',28,-40,'T7'),('S',B,'BS'),('A',420,+14,'T8'),('S',170,''),('A',480,+11,'T9'),('S',130,''),('A',44,-85,'T10a'),
    ('S',30,''),('A',52,+128,'T10b'),('S',S2,'S2'),('A',260,+10,'T11'),('S',90,''),('A',100,+90,'T12')]
def walk(F,B,S2,step=9.0):
    pr=prog(F,B,S2);th=0.0;x=y=0.0;pts=[(0,0,0,'FS',0.0)];s=0.0
    for e in pr:
        if e[0]=='S':
            n=max(1,int(e[1]/step));d=e[1]/n
            for i in range(n):
                x+=d*math.sin(math.radians(th));y+=d*math.cos(math.radians(th));s+=d;pts.append((x,y,th,e[2],s))
        else:
            ang=e[2];R=e[1];L=abs(math.radians(ang))*R;n=max(2,int(L/step));dth=ang/n;d=L/n
            for i in range(n):
                th+=dth/2;x+=d*math.sin(math.radians(th));y+=d*math.cos(math.radians(th));th+=dth/2;s+=d;pts.append((x,y,th,e[3],s))
    return pts
def err(v):
    p=walk(*v);return [p[-1][0],p[-1][1]]
sol=least_squares(lambda v:err(v),[420,300,300],bounds=([60,100,60],[900,1500,1400]))
print('lengths',sol.x,sol.fun,file=sys.stderr)
p=walk(*sol.x);Ltot=p[-1][4]
# elevation anchors (fraction of lap by feature midpoint) in metres
def mid(name):
    ss=[q[4] for q in p if q[3]==name];return (min(ss)+max(ss))/2/Ltot
ANC=[('FS',0.5,1),('T1',17),('T2',19),('T3',21),('T4',18),('E2',14),('T5',12),('T6',11),('T7',9),('BS',4),('T8',0),('T9',-4),('T10a',-7),('T10b',-9),('S2',-9),('T11',-11),('T12',-12)]
anchors=[]
anchors.append((0.0,-11))
for a in ANC:
    if a[0]=='FS':anchors.append((mid('FS')*0.55,4))
    else:anchors.append((mid(a[0]),a[1]))
anchors.append((1.0,-11))
anchors.sort()
def elev(f):
    f=min(max(f,0),1)
    for i in range(len(anchors)-1):
        a,b=anchors[i],anchors[i+1]
        if a[0]<=f<=b[0]:
            t=(f-a[0])/max(1e-9,b[0]-a[0]);t=t*t*(3-2*t);return a[1]+(b[1]-a[1])*t
    return anchors[-1][1]
out=[];feat={}
pt=p[:-1]  # last equals first (closed)
for i,q in enumerate(pt):
    x,y,th,name,s=q
    out.append([round(-x*SCALE,1),round(y*SCALE,1),round(elev(s/Ltot),1)])
    if name and name not in feat:feat[name]=[]
    if name:feat[name].append(i)
marks={}
for k,v in feat.items():marks[k]=v[len(v)//2]
ex=[]
for q in pt[::1]:ex.append(q)
data={'pts':out,'marks':marks,'L':round(Ltot*SCALE),'n':len(out)}
open('src/layers/ra_data.js','w').write('/* generated by tools/gen_ra.py */\nwindow.PT8_RA='+json.dumps(data,separators=(',',':'))+';\n')
print('points',len(out),'lap length m',round(Ltot*SCALE),'elev range',min(o[2] for o in out),max(o[2] for o in out),file=sys.stderr)
