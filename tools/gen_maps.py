#!/usr/bin/env python3
"""Rebuild the Road Atlanta and Imola centrelines from two layout map images (a black line map and a red line map).
Scales each loop to the real lap length (Road Atlanta 4,088 m, Imola 4,909 m) so 1 game unit = 1 m.
usage: gen_maps.py <ra_map.png> <imola_map.png> ; reads/writes src/layers/ra_data.js and imola_data.js"""
import sys,json,re,math,numpy as np
from PIL import Image
from scipy import ndimage as ndi
from scipy.ndimage import gaussian_filter1d
from skimage import measure
from scipy.spatial import cKDTree
def biggest(m):
    lab,n=ndi.label(m,structure=np.ones((3,3)));sz=ndi.sum(m,lab,range(1,n+1));return lab==(1+int(np.argmax(sz)))
def center(m,it):
    m=ndi.binary_dilation(m,structure=np.ones((3,3)),iterations=it)
    cs=sorted(measure.find_contours(np.pad(m.astype(float),2),0.5),key=len,reverse=True)[:2]
    A=cs[0][:,::-1]-2;B=cs[1][:,::-1]-2;_,j=cKDTree(B).query(A);return (A+B[j])/2
def resample(P,n):
    Q=np.vstack([P,P[:1]]);d=np.r_[0,np.cumsum(np.hypot(*np.diff(Q,axis=0).T))]
    t=np.linspace(0,d[-1],n,endpoint=False);return np.c_[np.interp(t,d,Q[:,0]),np.interp(t,d,Q[:,1])]
def plen(P):
    Q=np.vstack([P,P[:1]]);return float(np.hypot(*np.diff(Q,axis=0).T).sum())
def area(P):return 0.5*float(np.sum(P[:,0]*np.roll(P[:,1],-1)-np.roll(P[:,0],-1)*P[:,1]))
def load(path,kind):
    a=np.array(Image.open(path).convert('RGB')).astype(int)
    if kind=='blk':m=a.sum(2)<240
    else:
        r,g,b=a[...,0],a[...,1],a[...,2];m=(r>150)&(r-g>60)&(abs(g-b)<45)
        m=ndi.binary_closing(m,structure=np.ones((3,3)),iterations=2)
    m=ndi.binary_dilation(m,iterations=1) if kind=='blk' else m
    return biggest(m)
def build(path,kind,real,cw,start_px,it,n_out):
    P=center(load(path,kind),it);P=resample(P,600)
    P=np.c_[gaussian_filter1d(P[:,0],2.5,mode='wrap'),gaussian_filter1d(P[:,1],2.5,mode='wrap')]
    k=real/plen(P);P=P*k
    if (area(P)>0)!=cw:P=P[::-1]
    s=np.array(start_px)*k;i0=int(np.argmin(np.hypot(*(P-s).T)));P=np.roll(P,-i0,axis=0)
    return resample(P,int(round(real/12))),k
def cosint(f,anch):
    xs=[a[0] for a in anch]+[1.0];ys=[a[1] for a in anch]+[anch[0][1]]
    out=[]
    for u in f:
        for i in range(len(xs)-1):
            if xs[i]<=u<=xs[i+1]:
                t=(u-xs[i])/max(1e-9,xs[i+1]-xs[i]);t=(1-math.cos(math.pi*t))/2;out.append(ys[i]*(1-t)+ys[i+1]*t);break
        else:out.append(ys[-1])
    return out
ra_img,im_img=sys.argv[1],sys.argv[2]
# Road Atlanta: clockwise, start/finish on the right-hand side
old=json.loads(re.search(r'PT8_RA=(\{.*\});?\s*$',open('src/layers/ra_data.js').read(),re.S).group(1))
P,k=build(ra_img,'blk',4088,True,(213,119),1,0)
n=len(P);oy=np.array([p[2] for p in old['pts']]);fs=old['marks']['FS']
# elevation: the old profile (by fraction of lap from the start line), scaled to roughly 50 m of relief
f0=np.arange(n)/n;shift=(0.0)
y=np.interp(f0,np.arange(len(oy))/len(oy),oy)*1.5
# the traced loop starts at the line; old data starts FS samples before it, so keep that lead-in
lead=int(round(fs/len(oy)*n));P=np.roll(P,lead,axis=0);y=np.roll(y,lead)
pts=[[round(float(P[i,0]),1),round(float(P[i,1]),1),round(float(y[i]),1)] for i in range(n)]
marks={kk:int(round(v*n/len(oy))) for kk,v in old['marks'].items()}
open('src/layers/ra_data.js','w').write('/* generated by tools/gen_maps.py from a layout map: real 4,088 m lap, 1 unit = 1 m */\nwindow.PT8_RA='+json.dumps({'pts':pts,'marks':marks,'L':4088,'n':n},separators=(',',':'))+';\n')
print('RA',n,'pts scale m/px',round(k,2))
# Imola: anticlockwise, start line on the long top straight
P,k=build(im_img,'red',4909,False,(157,25),3,0)
n=len(P)
A=[(0,0),(0.08,-4),(0.13,-7),(0.30,-13),(0.43,3),(0.55,16),(0.68,21),(0.88,8)]
# anchors by pixel landmark -> arc fraction
def frac(px):
    s=np.array(px)*k;return int(np.argmin(np.hypot(*(P-s).T)))/n
lm=[((157,25),0),((73,30),-4),((62,45),-7),((22,120),-13),((88,122),3),((92,66),16),((155,70),21),((225,18),8)]
anch=sorted([(frac(p),e) for p,e in lm]);anch[0]=(0.0,0)
y=cosint(np.arange(n)/n,anch)
pts=[[round(float(P[i,0]),1),round(float(P[i,1]),1),round(float(y[i]),1),7.0] for i in range(n)]
open('src/layers/imola_data.js','w').write('/* Imola layout rebuilt from a layout map: real 4,909 m lap, 1 unit = 1 m. Centreline, elevation and width only. */\nwindow.PT8_IMOLA='+json.dumps({'pts':pts},separators=(',',':'))+';\n')
print('IM',n,'pts scale m/px',round(k,2),anch)
