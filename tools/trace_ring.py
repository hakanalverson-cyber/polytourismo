#!/usr/bin/env python3
"""Rebuild the Nordschleife centreline from a layout map image (black line map, north up).
The inside edge of the black loop is traced (so hooks like the Karussell come out as hairpins), scaled to the
real 20,832 m lap and resampled every 12 m. Elevation and widths are carried over from the previous data by lap fraction.
usage: trace_ring.py <map.png> ; rewrites src/layers/ring_data.js"""
import sys,json,re,numpy as np
from PIL import Image
from scipy import ndimage as ndi
from scipy.ndimage import gaussian_filter1d
from skimage import measure
LAP=20832;STEP=12
a=np.array(Image.open(sys.argv[1]).convert('RGB')).astype(int)
line=a.sum(2)<240
inside=ndi.binary_fill_holes(line)&~line
lab,n=ndi.label(inside);sz=ndi.sum(inside,lab,range(1,n+1));inner=lab==(1+int(np.argmax(sz)))
inner=ndi.binary_fill_holes(inner)  # text labels inside the loop are not track
c=max(measure.find_contours(np.pad(inner.astype(float),2),0.5),key=len)[:,::-1]-2   # (x,y) px
def resample(P,n):
    Q=np.vstack([P,P[:1]]);d=np.r_[0,np.cumsum(np.hypot(*np.diff(Q,axis=0).T))]
    t=np.linspace(0,d[-1],n,endpoint=False);return np.c_[np.interp(t,d,Q[:,0]),np.interp(t,d,Q[:,1])],d[-1]
P,L=resample(c,1400)
P=np.c_[gaussian_filter1d(P[:,0],2.2,mode='wrap'),gaussian_filter1d(P[:,1],2.2,mode='wrap')]
P,L=resample(P,1400);k=LAP/L;P=P*k
# start at the T13 grandstand, lap runs west into Hatzenbach
s=np.array([91,139])*k;i0=int(np.argmin(np.hypot(*(P-s).T)));P=np.roll(P,-i0,axis=0)
if P[5,0]>P[0,0]:P=P[::-1];P=np.roll(P,1,axis=0)
P,_=resample(P,int(round(LAP/STEP)));n=len(P)
P=P-P[0]
old=json.loads(re.search(r'PT8_RING=(\{.*\});?\s*$',open('src/layers/ring_data.js').read(),re.S).group(1))
op=np.array(old['pts']);on=len(op);f=np.arange(n)/n;fo=np.arange(on)/on
y=np.interp(f,fo,op[:,2],period=1);hw=np.interp(f,fo,op[:,3],period=1)
# corner positions: rough real distances from the line (km, lap 20.83), then nudged to the matching features on the traced map
KM={'START / FINISH':0,'HATZENBACH':0.9,'HOCHEICHEN':1.9,'QUIDDELBACHER HOHE':2.5,'FLUGPLATZ':2.95,'KOTTENBORN':3.4,'SCHWEDENKREUZ':4.0,
 'AREMBERG':4.55,'FUCHSROHRE':5.0,'ADENAUER FORST':5.75,'METZGESFELD':6.25,'KALLENHARD':6.9,'SPIEGELKURVE':7.3,'WEHRSEIFEN':7.75,
 'BREIDSCHEID':8.35,'EX-MUHLE':8.55,'LAUDA-LINKS':8.8,'BERGWERK':9.35,'KESSELCHEN':10.0,'MUTKURVE':11.0,'KLOSTERTAL':11.4,
 'STEILSTRECKE':11.65,'KARUSSELL':11.9,'HOHE ACHT':12.75,'HEDWIGSHOHE':13.1,'WIPPERMANN':13.35,'ESCHBACH':13.75,'BRUNNCHEN':14.15,
 'EISKURVE':14.55,'PFLANZGARTEN':15.2,'STEFAN-BELLOF-S':15.6,'SCHWALBENSCHWANZ':16.3,'KLEINES KARUSSELL':16.5,'GALGENKOPF':17.05,
 'DOTTINGER HOHE':17.6,'ANTONIUSBUCHE':19.6,'TIERGARTEN':20.2,'HOHENRAIN':20.5}
marks={kk:int(round(KM[kk]/20.832*n))%n for kk in old['marks']}
# the Karussell is the hook on the map: put it on the hook's tip (furthest south point between Klostertal and Hohe Acht)
q=list(range(marks['MUTKURVE'],marks['HOHE ACHT']));marks['KARUSSELL']=max(q,key=lambda i:P[i,1])
marks['KLOSTERTAL']=min(marks['KLOSTERTAL'],marks['KARUSSELL']-25);marks['STEILSTRECKE']=marks['KARUSSELL']-12
# elevation and width follow the corners: warp lap fraction so each corner keeps its old height
xs=sorted((marks[kk]/n,old['marks'][kk]/on) for kk in old['marks']);xs=[(0,0)]+[p for p in xs if p[0]>0]+[(1,1)]
fw=np.interp(f,[p[0] for p in xs],[p[1] for p in xs])
y=np.interp(fw,fo,op[:,2],period=1);hw=np.interp(fw,fo,op[:,3],period=1)
y=gaussian_filter1d(y,3,mode='wrap')
for _ in range(200):  # cap the grade at about 15 %
    dy=np.diff(np.r_[y,y[:1]]);bad=np.abs(dy)>STEP*.15
    if not bad.any():break
    y=gaussian_filter1d(y,1.2,mode='wrap')
pts=[[round(float(P[i,0]),1),round(float(P[i,1]),1),round(float(y[i]),1),round(float(hw[i]),2)] for i in range(n)]
open('src/layers/ring_data.js','w').write('/* generated by tools/trace_ring.py from a layout map: real 20,832 m lap, 12 m samples, 1 unit = 1 m */\nwindow.PT8_RING='+json.dumps({'pts':pts,'marks':marks},separators=(',',':'))+';\n')
# diagnostics
d=np.hypot(*np.diff(np.vstack([P,P[:1]]),axis=0).T)
from scipy.spatial import cKDTree
tr=cKDTree(P);pr=tr.query_pairs(70);close=[(i,j) for i,j in pr if min(abs(i-j),n-abs(i-j))>20]
print('n',n,'m/px',round(k,1),'step',round(d.mean(),2),'close pairs <70m',len(close))
tip=np.array([163.7,39.6])*k-np.array([91,139])*k*0  # rough Karussell hook tip in px*k before shift
import matplotlib;matplotlib.use('Agg');import matplotlib.pyplot as plt
fig=plt.figure(figsize=(8,8));plt.plot(P[:,0],P[:,1],'-k',lw=1);plt.gca().invert_yaxis();plt.axis('equal')
for kk,v in marks.items():plt.plot(P[v,0],P[v,1],'r.');plt.text(P[v,0],P[v,1],kk,fontsize=6)
plt.plot(P[0,0],P[0,1],'go');plt.plot(P[8,0],P[8,1],'g^');fig.savefig('tests/out/ring_map2.png',dpi=110)
