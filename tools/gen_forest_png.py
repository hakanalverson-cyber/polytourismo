#!/usr/bin/env python3
"""Paint the Nordschleife forest-edge backdrop (a strip of layered spruce and beech crowns with alpha) and
write it as a PNG data URI into src/layers/ring_forest.js. Own artwork, generated here, no external assets."""
import base64,io,math,random
from PIL import Image,ImageDraw,ImageFilter
W,H=1024,256;random.seed(7)
img=Image.new('RGBA',(W,H),(0,0,0,0));d=ImageDraw.Draw(img)
def spruce(cx,base,h,w,col,shade,light):
    # stacked triangles, darker on the left, lit tips on the right
    tiers=7
    for t in range(tiers):
        f=t/tiers;y0=base-h*f*0.92;y1=y0-h*0.30;ww=w*(1-f*0.82)
        d.polygon([(cx-ww,y0),(cx+ww,y0),(cx,y1)],fill=col)
        d.polygon([(cx-ww,y0),(cx-ww*0.15,y0),(cx,y1)],fill=shade)
        d.polygon([(cx+ww*0.35,y0-1),(cx+ww,y0),(cx+ww*0.1,y1+h*0.08)],fill=light)
def beech(cx,base,r,col,shade,light):
    for k in range(9):
        a=random.random()*math.tau;rr=r*(0.45+random.random()*0.5);x=cx+math.cos(a)*r*0.55;y=base-r*1.1+math.sin(a)*r*0.45
        d.ellipse([x-rr,y-rr*0.85,x+rr,y+rr*0.85],fill=col)
    for k in range(5):
        x=cx+(random.random()-.3)*r*0.8;y=base-r*1.4+random.random()*r*0.5;rr=r*0.35
        d.ellipse([x-rr,y-rr*0.8,x+rr,y+rr*0.8],fill=light)
    d.ellipse([cx-r*0.9,base-r*0.9,cx+r*0.2,base-r*0.1],fill=shade)
# three depth rows: back (bluish, tall), middle, front (rich green); every row wraps across the seam
rows=[(150,(38,74,58),(30,60,50),(56,96,74),1.15,0.55),(190,(28,82,44),(20,62,34),(58,118,60),1.0,0.5),(232,(24,92,38),(16,66,28),(70,140,58),0.9,0.42)]
for base,col,shade,light,hs,mix in rows:
    x=-40
    while x<W+40:
        if random.random()<mix:
            h=(95+random.random()*70)*hs;w=h*0.24
            for ox in (0,-W,W):spruce(x+ox,base+random.random()*8,h,w,col,shade,light)
        else:
            r=(30+random.random()*22)*hs
            c2=(col[0]+18,col[1]+22,col[2]-6);l2=(light[0]+30,light[1]+28,light[2]-10)
            for ox in (0,-W,W):beech(x+ox,base+6,r,c2,shade,l2)
        x+=14+random.random()*20
# ground band under the front row: dark undergrowth so the strip sits into the grass
d.rectangle([0,232,W,H],fill=(18,48,24,255))
for k in range(260):
    x=random.random()*W;y=226+random.random()*14;r=4+random.random()*8
    d.ellipse([x-r,y-r*0.6,x+r,y+r*0.6],fill=(26+random.randint(0,14),70+random.randint(0,20),32,255))
a=img.split()[3].point(lambda v:255 if v>100 else 0);img.putalpha(a)
q=img.convert('RGB').quantize(96,method=Image.Quantize.MEDIANCUT).convert('RGB');q.putalpha(a)
buf=io.BytesIO();q.save(buf,'PNG',optimize=True);b=buf.getvalue()
q.save('tests/out/ring_forest.png')
open('src/layers/ring_forest.js','w').write('/* generated by tools/gen_forest_png.py: forest-edge backdrop for the Nordschleife (own artwork) */\nwindow.PT8_RING_FOREST="data:image/png;base64,'+base64.b64encode(b).decode()+'";\n')
print('png bytes',len(b))
